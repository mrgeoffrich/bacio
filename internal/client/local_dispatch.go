// resolveBaseBranchForIssueKey is the BACI-226 resolver entry point
// for the targeted-pending dispatch creation paths: given the
// caller's issue_key (which may legitimately be empty for an
// issue-less dispatch like a setup nudge), load the issue + its
// optional feature and resolve via model.ResolveBaseBranch. Returns
// "" when the issue_key is empty so the stub omits the
// <base_branch> tag (no PR to target) — read sites use the
// resolver's fallback to recover a usable value.
func (c *localClient) resolveBaseBranchForIssueKey(ctx context.Context, repo *model.Repo, issueKey string) (string, error) {
	if issueKey == "" {
		return "", nil
	}
	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return "", err
	}
	return c.resolveBaseBranchForIssue(iss), nil
}

// resolveBaseBranchForIssue is the BACI-226 resolver pass once an
// issue is already in hand (the auto-dispatch path, the TUI picker,
// etc.). Falls back to model.DefaultBaseBranch when the feature
// lookup fails — the resolver's invariant is "never empty" and
// blocking the dispatch on a vanished feature would be punitive for
// what is purely a derived field.
func (c *localClient) resolveBaseBranchForIssue(iss *model.Issue) string {
	if iss == nil {
		return model.DefaultBaseBranch
	}
	var feat *model.Feature
	if iss.FeatureID != nil {
		f, err := c.store.GetFeatureByID(*iss.FeatureID)
		if err == nil {
			feat = f
		}
	}
	return model.ResolveBaseBranch(iss, feat)
}

func (c *localClient) CreateDispatch(ctx context.Context, repo *model.Repo, in inputs.AgentDispatchInput, dryRun bool) (*model.AgentDispatch, error) {
	if in.TargetAgent == "" && in.TargetSession == "" {
		return nil, fmt.Errorf("dispatch requires a target — pass --to <agent> and/or --session <id>")
	}

	var agentID *int64
	if in.TargetAgent != "" {
		ag, err := c.store.GetAgentByName(in.TargetAgent)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return nil, fmt.Errorf("no agent identity named %q is registered", in.TargetAgent)
			}
			return nil, err
		}
		agentID = &ag.ID
	}
	if in.TargetSession != "" {
		if _, err := c.store.GetAgentSession(in.TargetSession); err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return nil, fmt.Errorf("session %q is not registered", in.TargetSession)
			}
			return nil, err
		}
	}

	var issueID *int64
	var issueKey string
	if in.IssueKey != "" {
		iss, err := c.GetIssueByKey(ctx, repo, in.IssueKey)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return nil, fmt.Errorf("issue %s does not exist in repo %s", in.IssueKey, repo.Prefix)
			}
			return nil, err
		}
		issueID = &iss.ID
		issueKey = iss.Key
	}

	mode := model.DispatchMode(in.Mode)
	// BACI-76: the per-mode brief no longer goes in the dispatch
	// payload — it is the per-mode subagent's system prompt now
	// (`.claude/agents/bacio-<mode>-worker.md`, generated by
	// `bacio install-agent`). The payload is the rewritten preamble
	// (telling the supervisor to spawn that subagent) plus a tiny stub
	// naming the ticket, mode, and subagent type. An untyped mode
	// produces no stub, so the payload is just the free-form note.
	preamble, err := c.store.GetDispatchPreamble()
	if err != nil {
		return nil, err
	}
	// BACI-226: stamp <base_branch> into the stub at creation time so
	// targeted-pending dispatches (which never go through the matcher
	// bind step) carry the correct value from the start. Queued
	// dispatches re-render at BindQueuedDispatch with the bind-time
	// resolved value, but seeding the initial render here keeps the
	// pre-bind payload coherent for any consumer that reads it before
	// the matcher fires.
	baseBranch, err := c.resolveBaseBranchForIssueKey(ctx, repo, in.IssueKey)
	if err != nil {
		return nil, err
	}
	stub := model.DispatchStub{IssueKey: issueKey, Mode: string(mode), BaseBranch: baseBranch}
	if mode != "" {
		stub.SubagentType = model.SubagentTypeForTemplate(string(mode))
	}
	payload := model.ComposeDispatchPayload(preamble, stub, in.Message)

	if dryRun {
		return &model.AgentDispatch{
			RepoID:          repo.ID,
			RepoPrefix:      repo.Prefix,
			TargetAgentID:   agentID,
			TargetAgentName: in.TargetAgent,
			TargetSessionID: in.TargetSession,
			IssueID:         issueID,
			IssueKey:        issueKey,
			Mode:            mode,
			Payload:         payload,
			Status:          model.DispatchPending,
			CreatedBy:       c.actor,
			CreatedAt:       time.Now().UTC(),
		}, nil
	}

	d, err := c.store.AddDispatch(store.AddDispatchIn{
		RepoID:          repo.ID,
		TargetAgentID:   agentID,
		TargetSessionID: in.TargetSession,
		IssueID:         issueID,
		Mode:            mode,
		Payload:         payload,
		CreatedBy:       c.actor,
	})
	if err != nil {
		return nil, err
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.dispatch", Kind: "agent",
		TargetID: &d.ID, TargetLabel: dispatchTargetLabel(d),
		Details: dispatchDetails(d),
	})
	return d, nil
}

// AutoDispatchIssue (BACI-40, rewired by BACI-51) is the state-gated
// auto-pick dispatch verb shared by the desktop per-card action button,
// the REST `POST /repos/{prefix}/issues/{key}/dispatch` route, and the
// CLI's target-less `bacio agent dispatch <key> --mode <stage>`.
//
// As of BACI-51 this is the **enqueue path**: it re-checks the mode's
// state-gate, then inserts a target-less `queued` dispatch the
// background matcher will bind to a free agent when one frees up.
// Never errors with "no free agent" — that case is now expressed as a
// queued row in the per-(repo, mode) FIFO. Targeted dispatches
// (CreateDispatch with --to/--session) still go straight to pending.
func (c *localClient) AutoDispatchIssue(ctx context.Context, repo *model.Repo, issueKey, mode string, dryRun bool) (*model.AgentDispatch, error) {
	if repo == nil {
		return nil, fmt.Errorf("AutoDispatchIssue requires a repo")
	}
	parsedMode, err := model.ParseDispatchMode(mode)
	if err != nil {
		return nil, err
	}
	if parsedMode == "" {
		return nil, fmt.Errorf("a dispatch mode is required")
	}

	// State-gate: the prompt for this stage must be valid to run from
	// the issue's current state. The desktop UI already gates the
	// per-card action button on this; re-check here so a stale UI or
	// a CLI/REST caller can't queue a prompt the state doesn't allow.
	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return nil, err
	}
	// BACI-68: refuse to dispatch an archived issue. The kanban card
	// for an archived todo wouldn't render an action button by default,
	// but the REST/CLI entry points (and a stale desktop view) could
	// still send a dispatch through — block it here so the manual
	// archive lever isn't quietly bypassed.
	if iss.ArchivedAt != nil {
		return nil, fmt.Errorf("issue %s is archived; unarchive it before dispatching", iss.Key)
	}
	gates, err := c.GetPromptStates(ctx)
	if err != nil {
		return nil, err
	}
	if !slices.Contains(gates[mode], string(iss.State)) {
		return nil, fmt.Errorf("the %s prompt can't run from a %s issue", mode, iss.State)
	}

	// BACI-76: the queued dispatch carries the rewritten preamble plus
	// a tiny stub (ticket / mode / subagent type) — not the full
	// per-mode brief, which is now the subagent's system prompt. The
	// matcher's later bind + drain hands this short payload to the
	// supervisor, which spawns the named per-mode subagent.
	preamble, err := c.store.GetDispatchPreamble()
	if err != nil {
		return nil, err
	}
	// BACI-226: render <base_branch> into the queue-time stub using
	// the resolver against the current issue + feature. The matcher
	// re-renders the payload at BindQueuedDispatch using the freshly-
	// resolved bind-time value (which is also the value the BACI-227
	// concurrency cap groups by), so a per-issue / per-feature override
	// added between queue and bind still reaches the worker.
	baseBranch := c.resolveBaseBranchForIssue(iss)
	payload := model.ComposeDispatchPayload(preamble, model.DispatchStub{
		IssueKey:     iss.Key,
		Mode:         string(parsedMode),
		BaseBranch:   baseBranch,
		SubagentType: model.SubagentTypeForTemplate(string(parsedMode)),
	}, "")

	if dryRun {
		return &model.AgentDispatch{
			RepoID:     repo.ID,
			RepoPrefix: repo.Prefix,
			IssueID:    &iss.ID,
			IssueKey:   iss.Key,
			Mode:       parsedMode,
			Payload:    payload,
			BaseBranch: baseBranch,
			Status:     model.DispatchQueued,
			CreatedBy:  c.actor,
			CreatedAt:  time.Now().UTC(),
		}, nil
	}

	d, err := c.store.AddDispatch(store.AddDispatchIn{
		RepoID:        repo.ID,
		IssueID:       &iss.ID,
		Mode:          parsedMode,
		Payload:       payload,
		CreatedBy:     c.actor,
		InitialStatus: model.DispatchQueued,
	})
	if err != nil {
		return nil, err
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.queue", Kind: "agent",
		TargetID: &d.ID, TargetLabel: iss.Key,
		Details: dispatchDetails(d),
	})
	return d, nil
}

// AutoDispatchIssueWithFollowOn (BACI-209) is the compound enqueue verb
// that writes a primary queued dispatch AND a dormant follow-on linked
// to it, both in one store transaction. The desktop kanban's
// "Plan, then Implement" picker is the first caller; the REST route
// `POST /repos/{prefix}/issues/{key}/dispatch-chain` and
// `bacio agent dispatch-chain` all route through here so the
// gate + payload + audit-row shape stays in one place.
//
// Semantics:
//   - The primary state-gate is re-checked against the issue's current
//     state — same as AutoDispatchIssue. A gate-miss returns an error
//     before any insert.
//   - The follow-on's gate is NOT checked here. Same posture as
//     QueueFollowOnDispatch (BACI-195): the gate runs at fire time
//     when the controller's promote sweep clears the dormant link.
//     Queueing `implement` while the parent is still planning is the
//     canonical case the dropped queue-time gate enabled.
//   - Two audit rows: `agent.queue` for the parent (same as
//     AutoDispatchIssue's emit) plus `agent.followon.queue` for the
//     dormant follow-on. Existing `bacio history --op` queries keep
//     working unchanged.
//   - dry-run projects both rows without touching the DB. The caller
//     emits the parent's projection (the kanban primary affordance);
//     the follow-on rides on the next BoardCard refresh via
//     card.followOn.
func (c *localClient) AutoDispatchIssueWithFollowOn(ctx context.Context, repo *model.Repo, issueKey, mode, followOnMode string, dryRun bool) (parent, followOn *model.AgentDispatch, err error) {
	if repo == nil {
		return nil, nil, fmt.Errorf("AutoDispatchIssueWithFollowOn requires a repo")
	}
	parsedMode, err := model.ParseDispatchMode(mode)
	if err != nil {
		return nil, nil, err
	}
	if parsedMode == "" {
		return nil, nil, fmt.Errorf("a dispatch mode is required")
	}
	parsedFollow, err := model.ParseDispatchMode(followOnMode)
	if err != nil {
		return nil, nil, err
	}
	if parsedFollow == "" {
		return nil, nil, fmt.Errorf("a follow-on dispatch mode is required")
	}
	if parsedFollow == parsedMode {
		// Defence at the boundary — the UI's dropdown skips the same-mode
		// pair, but a stale UI / CLI caller might still send one. Chaining
		// the same mode is meaningless (the controller's gate sweep would
		// either re-queue the same work or gate-fail-cancel it).
		return nil, nil, fmt.Errorf("follow-on mode %q matches the primary mode; pick a different next stage", parsedFollow)
	}

	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return nil, nil, err
	}
	if iss.ArchivedAt != nil {
		return nil, nil, fmt.Errorf("issue %s is archived; unarchive it before dispatching", iss.Key)
	}
	gates, err := c.GetPromptStates(ctx)
	if err != nil {
		return nil, nil, err
	}
	if !slices.Contains(gates[mode], string(iss.State)) {
		return nil, nil, fmt.Errorf("the %s prompt can't run from a %s issue", mode, iss.State)
	}

	// Compose the parent's payload the same way AutoDispatchIssue does —
	// preamble + a stub naming the ticket, mode, and subagent type.
	preamble, err := c.store.GetDispatchPreamble()
	if err != nil {
		return nil, nil, err
	}
	// BACI-226: same base-branch handling as AutoDispatchIssue's
	// single-row path. The chain's follow-on row is bound by the
	// matcher later and re-rendered at bind time, so we only need to
	// seed the parent's payload here.
	baseBranch := c.resolveBaseBranchForIssue(iss)
	payload := model.ComposeDispatchPayload(preamble, model.DispatchStub{
		IssueKey:     iss.Key,
		Mode:         string(parsedMode),
		BaseBranch:   baseBranch,
		SubagentType: model.SubagentTypeForTemplate(string(parsedMode)),
	}, "")

	if dryRun {
		now := time.Now().UTC()
		projParent := &model.AgentDispatch{
			RepoID:     repo.ID,
			RepoPrefix: repo.Prefix,
			IssueID:    &iss.ID,
			IssueKey:   iss.Key,
			Mode:       parsedMode,
			Payload:    payload,
			Status:     model.DispatchQueued,
			CreatedBy:  c.actor,
			CreatedAt:  now,
		}
		// The dry-run projection can't know the parent's id yet (no
		// INSERT ran), so QueuedAfterDispatchID is left nil on the
		// projected follow-on — same shape QueueFollowOnDispatch's
		// dry-run would produce against a not-yet-inserted parent.
		projFollow := &model.AgentDispatch{
			RepoID:     repo.ID,
			RepoPrefix: repo.Prefix,
			IssueID:    &iss.ID,
			IssueKey:   iss.Key,
			Mode:       parsedFollow,
			Status:     model.DispatchQueued,
			CreatedBy:  c.actor,
			CreatedAt:  now,
		}
		return projParent, projFollow, nil
	}

	parent, followOn, err = c.store.AddDispatchWithFollowOn(store.AddDispatchWithFollowOnIn{
		RepoID:       repo.ID,
		IssueID:      &iss.ID,
		Mode:         parsedMode,
		Payload:      payload,
		CreatedBy:    c.actor,
		FollowOnMode: parsedFollow,
	})
	if err != nil {
		return nil, nil, err
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.queue", Kind: "agent",
		TargetID: &parent.ID, TargetLabel: iss.Key,
		Details: dispatchDetails(parent),
	})
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.followon.queue", Kind: "agent",
		TargetID: &followOn.ID, TargetLabel: iss.Key,
		Details: followOnDetailsForClient(followOn),
	})
	return parent, followOn, nil
}

// QueueFollowOnDispatch (BACI-179, BACI-195) queues a dormant follow-on
// dispatch against an issue's currently-in-flight (parent) dispatch.
// Resolves the parent via WaitingDispatchForIssue — the open dispatch
// the claimed issue is wearing — then delegates to
// store.AddFollowOnDispatch for the validate+insert. Returns the new
// dormant row.
//
// Validates the mode (must be parseable, must be non-empty). NB: the
// state-gate is **not** checked here — the whole point of a follow-on
// is to queue the *next* mode while the current one is still running,
// so the issue is almost always in a state the next-mode gate doesn't
// admit at queue time (e.g. queueing `implement` while a research-mode
// parent has the issue in_progress; implement's gate is `todo`). The
// gate is re-evaluated at **fire time** by the controller's promote
// sweep, which sees the issue's post-release state and either promotes
// the row to a regular queued dispatch (gate passes) or cancels it
// with op=agent.followon.gate_fail (gate fails). BACI-195 dropped the
// queue-time check that was previously here — see the matching
// fire-time logic in store.PromoteReadyFollowOns /
// controller.FollowOnSweepIfLeader.
//
// Writes one `agent.followon.queue` audit row attributed to the
// calling actor (vs the orphan-cancel sweep's bacio-controller
// attribution) so `bacio history --op agent.followon.queue` records
// who queued each follow-on.
//
// Phase 1 callers go through this method directly (e.g. tests / phase
// 2 wiring); Phase 2 promotes it to the Client interface so the CLI
// and REST surface share the same path.
func (c *localClient) QueueFollowOnDispatch(ctx context.Context, repo *model.Repo, issueKey string, mode string, dryRun bool) (*model.AgentDispatch, error) {
	if repo == nil {
		return nil, fmt.Errorf("QueueFollowOnDispatch requires a repo")
	}
	parsedMode, err := model.ParseDispatchMode(mode)
	if err != nil {
		return nil, err
	}
	if parsedMode == "" {
		return nil, fmt.Errorf("a dispatch mode is required")
	}
	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return nil, err
	}
	parent, err := c.store.WaitingDispatchForIssue(repo.ID, iss.ID)
	if err != nil {
		return nil, err
	}
	if parent != nil {
		// Parent-acks variant: an in-flight dispatch is already on the
		// issue, queue the follow-on linked to it (BACI-179 path).
		if dryRun {
			// Project the would-be row — mirrors AutoDispatchIssue's dry-run
			// shape so the caller sees the same fields as a real insert.
			return &model.AgentDispatch{
				RepoID:                repo.ID,
				RepoPrefix:            repo.Prefix,
				IssueID:               &iss.ID,
				IssueKey:              iss.Key,
				Mode:                  parsedMode,
				Status:                model.DispatchQueued,
				CreatedBy:             c.actor,
				CreatedAt:             time.Now().UTC(),
				QueuedAfterDispatchID: &parent.ID,
			}, nil
		}
		d, err := c.store.AddFollowOnDispatch(repo.ID, parent.ID, parsedMode, c.actor)
		if err != nil {
			return nil, err
		}
		c.recordOp(model.HistoryEntry{
			RepoID: &repo.ID, RepoPrefix: repo.Prefix,
			Op: "agent.followon.queue", Kind: "agent",
			TargetID: &d.ID, TargetLabel: iss.Key,
			Details: followOnDetailsForClient(d),
		})
		return d, nil
	}
	// BACI-217: no in-flight parent dispatch — fall through to the
	// blockers-clear variant if the issue is blocked by at least one
	// open issue. Either branch lands an `agent.followon.queue` audit
	// row with the gate stamped in Details; an issue that is neither
	// in-flight nor blocked keeps today's error message verbatim.
	blockers, err := c.store.BlockersFor([]int64{iss.ID})
	if err != nil {
		return nil, err
	}
	openBlockers := 0
	for _, b := range blockers[iss.ID] {
		if b.BlockerState != model.StateDone && b.BlockerState != model.StateCancelled {
			openBlockers++
		}
	}
	if openBlockers == 0 {
		return nil, fmt.Errorf("issue %s has no active dispatch to follow on from", iss.Key)
	}
	if dryRun {
		// Project the would-be blockers-clear row — same shape as the
		// parent-acks dry-run, but with the blockers flag set and the
		// parent-id absent. The chip's "blocked by N" label is derived
		// server-side at next BoardCard refresh.
		return &model.AgentDispatch{
			RepoID:                   repo.ID,
			RepoPrefix:               repo.Prefix,
			IssueID:                  &iss.ID,
			IssueKey:                 iss.Key,
			Mode:                     parsedMode,
			Status:                   model.DispatchQueued,
			CreatedBy:                c.actor,
			CreatedAt:                time.Now().UTC(),
			QueuedUntilBlockersClear: true,
		}, nil
	}
	d, err := c.store.AddBlockerFollowOnDispatch(repo.ID, iss.ID, parsedMode, c.actor)
	if err != nil {
		return nil, err
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.followon.queue", Kind: "agent",
		TargetID: &d.ID, TargetLabel: iss.Key,
		Details: followOnDetailsForClient(d),
	})
	return d, nil
}

// CancelFollowOnDispatch (BACI-179) cancels the dormant follow-on
// attached to an issue. Idempotent: returns (nil, nil) when there is
// nothing to cancel. Writes one `agent.followon.cancel` audit row
// attributed to the calling actor when a row actually flipped — the
// orphan-cancel sweep writes the same op with `bacio-controller` as
// the actor so `bacio history --op agent.followon.cancel` distinguishes
// the two paths.
func (c *localClient) CancelFollowOnDispatch(ctx context.Context, repo *model.Repo, issueKey string, dryRun bool) (*model.AgentDispatch, error) {
	if repo == nil {
		return nil, fmt.Errorf("CancelFollowOnDispatch requires a repo")
	}
	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return nil, err
	}
	existing, err := c.store.FollowOnForIssue(repo.ID, iss.ID)
	if err != nil {
		return nil, err
	}
	if existing == nil {
		// Idempotent no-op — mirror CancelDispatch's already-cancelled path.
		return nil, nil
	}
	if dryRun {
		proj := *existing
		proj.Status = model.DispatchCancelled
		return &proj, nil
	}
	cancelled, err := c.store.CancelFollowOnDispatch(repo.ID, iss.ID)
	if err != nil {
		return nil, err
	}
	if cancelled == nil {
		// Raced with the orphan-cancel sweep — that sweep already wrote
		// its own audit row, nothing to add here.
		return nil, nil
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &repo.ID, RepoPrefix: repo.Prefix,
		Op: "agent.followon.cancel", Kind: "agent",
		TargetID: &cancelled.ID, TargetLabel: iss.Key,
		Details: followOnDetailsForClient(cancelled),
	})
	return cancelled, nil
}

// followOnDetailsForClient composes the audit-log Details string for
// client-driven follow-on ops (queue / cancel). Mirrors the
// controller-side followOnDetails helper — kept package-local here so
// the client doesn't import the controller package just for the
// helper. Same shape so a reader of `bacio history --op
// agent.followon.queue` sees identical fields regardless of which
// writer the row came from. BACI-217: also stamps `gate=parent` /
// `gate=blockers` so the audit log distinguishes the two variants.
func followOnDetailsForClient(d *model.AgentDispatch) string {
	if d == nil {
		return ""
	}
	parts := []string{fmt.Sprintf("dispatch_id=%d", d.ID)}
	if d.IssueKey != "" {
		parts = append(parts, "issue="+d.IssueKey)
	}
	if d.Mode != "" {
		parts = append(parts, "mode="+string(d.Mode))
	}
	if d.QueuedAfterDispatchID != nil {
		parts = append(parts, fmt.Sprintf("parent_dispatch_id=%d", *d.QueuedAfterDispatchID))
		parts = append(parts, "gate=parent")
	} else if d.QueuedUntilBlockersClear {
		parts = append(parts, "gate=blockers")
	}
	return strings.Join(parts, ",")
}

// WaitingDispatchForIssue returns the active (queued/pending/delivered)
// dispatch targeting an issue or (nil, nil) if none. Backs the
// spinner-as-cancel UI added in BACI-51.
func (c *localClient) WaitingDispatchForIssue(ctx context.Context, repo *model.Repo, issueKey string) (*model.AgentDispatch, error) {
	if repo == nil {
		return nil, fmt.Errorf("WaitingDispatchForIssue requires a repo")
	}
	iss, err := c.GetIssueByKey(ctx, repo, issueKey)
	if err != nil {
		return nil, err
	}
	return c.store.WaitingDispatchForIssue(repo.ID, iss.ID)
}

// InflightByModeForRepo (BACI-145) is the bulked sibling of
// CountInFlightByMode — one read per repo for the kanban / brief
// assembler's WaitingState derivation. Modes with zero in-flight rows
// are omitted from the map.
//
