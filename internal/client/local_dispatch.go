func (c *localClient) CancelDispatch(ctx context.Context, in inputs.AgentCancelInput, dryRun bool) (*model.AgentDispatch, error) {
	d, err := c.store.GetDispatch(in.ID)
	if err != nil {
		if errors.Is(err, store.ErrNotFound) {
			return nil, fmt.Errorf("no dispatch with id %d", in.ID)
		}
		return nil, err
	}
	if d.Status == model.DispatchAcked {
		return nil, fmt.Errorf("dispatch %d is already acked; cannot cancel", in.ID)
	}
	// BACI-130: a delivered dispatch is past the point where cancelling
	// the row does anything useful — the worker has the Task in hand
	// and the work is happening. Mirror the store-level reject here so
	// `--dry-run` reports the conflict instead of synthesising a
	// "would-be cancelled" projection.
	if d.Status == model.DispatchDelivered {
		return nil, fmt.Errorf("dispatch %d has been delivered; cannot cancel", in.ID)
	}
	if dryRun {
		proj := *d
		proj.Status = model.DispatchCancelled
		return &proj, nil
	}
	cancelled, err := c.store.CancelDispatch(in.ID)
	if err != nil {
		return nil, err
	}
	c.recordOp(model.HistoryEntry{
		RepoID: &cancelled.RepoID, RepoPrefix: cancelled.RepoPrefix,
		Op: "agent.cancel", Kind: "agent",
		TargetID: &cancelled.ID, TargetLabel: dispatchTargetLabel(cancelled),
		Details: dispatchDetails(cancelled),
	})
	return cancelled, nil
}

func (c *localClient) DrainDispatches(ctx context.Context, sessionID string) ([]*model.AgentDispatch, error) {
	sess, err := c.store.GetAgentSession(sessionID)
	if err != nil {
		if errors.Is(err, store.ErrNotFound) {
			return nil, fmt.Errorf("session %q is not registered", sessionID)
		}
		return nil, err
	}
	// Drain pending AND delivered — anything not yet acked. `delivered`
	// only means "we tried to hand it over once"; if that push was lost
	// (a dead channel process, a notification the session never surfaced)
	// the dispatch would be silently stranded. Re-surfacing un-acked
	// dispatches on every hook drain is the reliable recovery path — only
	// an ack retires a dispatch.
	open, err := c.store.ListDispatches(store.DispatchFilter{
		TargetAgentID:   sess.AgentID,
		TargetSessionID: sess.SessionID,
		Statuses:        []model.DispatchStatus{model.DispatchPending, model.DispatchDelivered},
	})
	if err != nil {
		return nil, err
	}
	return c.markDrained(open, sess.SessionID)
}

// markDrained flips any still-pending dispatches to delivered and returns
// the list unchanged otherwise. Already-delivered rows are passed through
// as-is (re-emitted by the caller until acked).
//
// BACI-160 gap 3: writes one `agent.deliver` history row per successful
// pending→delivered transition. Without this the moment a dispatch
// first reaches the worker is invisible in `bacio history` — readers
// would have to JOIN agent_dispatches.delivered_at instead of filtering
// the audit log by op. Only the in-loop pending check gates the audit
// write (already-delivered rows fall to the unchanged-passthrough
// branch above and never re-stamp).
//
// BACI-202: every pending→delivered emission is gated on a per-
// (dispatch, session) uniqueness claim against `dispatch_deliveries`.
// Two sessions sharing one agent identity (different claude_pid, same
// target_agent_id) would otherwise both surface the same dispatch
// through ListDispatches's agent-id-OR-session-id filter and double-
// deliver it. The losing session's drain falls through silently — no
// MarkDispatchDelivered call, no agent.deliver audit row, no entry in
// the returned slice — and the BACI-202 `dispatch_deliveries` row that
// the WINNING session inserted is the storage-layer source of truth
// for the uniqueness invariant. An empty sessionID short-circuits the
// gate so the legacy `DrainAgentDispatches` shape (which has no live
// callers but stays in the Client interface for symmetry) still
// drains to delivered without uniqueness gating.
func (c *localClient) markDrained(open []*model.AgentDispatch, sessionID string) ([]*model.AgentDispatch, error) {
	out := make([]*model.AgentDispatch, 0, len(open))
	for _, d := range open {
		if d.Status == model.DispatchPending {
			// BACI-202: claim the per-(dispatch, session) delivery slot
			// BEFORE the status flip + audit write. The losing session
			// of two concurrent drains gets claimed=false here and
			// skips the rest of this branch entirely.
			if sessionID != "" {
				claimed, err := c.store.ClaimDispatchDelivery(d.ID, sessionID)
				if err != nil {
					return nil, err
				}
				if !claimed {
					continue
				}
			}
			delivered, err := c.store.MarkDispatchDelivered(d.ID)
			if err != nil {
				return nil, err
			}
			c.recordOp(model.HistoryEntry{
				RepoID: &delivered.RepoID, RepoPrefix: delivered.RepoPrefix,
				Op: "agent.deliver", Kind: "agent",
				TargetID: &delivered.ID, TargetLabel: dispatchTargetLabel(delivered),
				Details: dispatchDetails(delivered),
			})
			out = append(out, delivered)
			continue
		}
		out = append(out, d)
	}
	return out, nil
}

